"""Урок L7.2 — Генераторы: тот же итератор, но в две строки.

Генератор — это функция, в которой вместо return стоит yield. Такая функция
при вызове НЕ выполняет тело, а возвращает готовый итератор. Каждое yield
выдаёт одно значение и ставит функцию на паузу; следующий next() продолжает
с того же места, со всеми локальными переменными на месте.

Главная практическая ценность - ЛЕНИВОСТЬ: значения считаются по одному, по
требованию. Поэтому генератором можно обработать файл на 10 ГБ или поток
данных, который вообще не кончается, не съев при этом память.
"""

import sys


def countdown(start: int):
    """Ровно тот же обратный отсчёт, что класс Countdown из файла 01."""
    while start > 0:
        yield start             # выдали значение и встали на паузу
        start -= 1
    # функция дошла до конца -> генератор сам бросает StopIteration


def noisy():
    """Печатает, где именно выполняется код: видно, что тело - ленивое."""
    print("    ... начало тела функции")
    yield 1
    print("    ... продолжили после первого yield")
    yield 2
    print("    ... продолжили после второго yield")


def squares_list(n: int) -> list:
    """Считает ВСЁ сразу и держит в памяти список."""
    result = []
    for x in range(n):
        result.append(x * x)
    return result


def squares_gen(n: int):
    """Считает по одному значению за раз, ничего не хранит."""
    for x in range(n):
        yield x * x


def new_id(start: int = 1):
    """Бесконечный генератор: у списка так не получится, а тут - легко."""
    while True:                 # бесконечный цикл здесь безопасен:
        yield start             # значения выдаются только когда их просят
        start += 1


def demo2():
    print("== 02. Генераторы (yield) ==\n")

    print("-- генератор вместо класса-итератора --")
    print("  list(countdown(5)) =", list(countdown(5)))

    print("\n-- вызов функции тело НЕ выполняет --")
    gen = noisy()               # ни одной строки тела ещё не выполнилось
    print("  создали генератор:", type(gen).__name__)
    print("  next(gen) =", next(gen))
    print("  next(gen) =", next(gen))
    try:
        next(gen)
    except StopIteration:
        print("  next(gen) -> StopIteration, генератор закончился")

    print("\n-- память: список против генератора (1 млн значений) --")
    as_list = squares_list(1_000_000)
    as_gen = squares_gen(1_000_000)
    print("  список   :", sys.getsizeof(as_list), "байт (и это только сам список,")
    print("             без миллиона объектов-чисел внутри - на деле больше)")
    print("  генератор:", sys.getsizeof(as_gen), "байт, сколько бы значений ни было")
    print("  суммы совпадают:", sum(as_gen) == sum(as_list))

    print("\n-- бесконечный генератор + break --")
    for number in new_id():
        if number > 5:
            break               # без break цикл бы не кончился никогда
        print("  выдан id:", number)

    print("\n-- чего генератор НЕ умеет --")
    gen = squares_gen(5)
    print("  print(gen) печатает не значения, а объект:", gen)
    print("  len(gen) и gen[0] не работают: длина заранее неизвестна")
    print(f"  берем элемент 1 раз: next(gen) = {next(gen)}")
    print("  нужен список - оберни: list(gen) =", list(gen))
    print("  и он одноразовый: второй list(gen) =", list(gen))

    print("\nИтог: yield превращает функцию в ленивый источник значений.")
    print("Правило: нужен весь набор сразу - список; надо пройти один раз,")
    print("данных много или они бесконечны - генератор.")


if __name__ == "__main__":
    demo2()
