"""Урок L7.3 — Генераторные выражения: генератор в одну строку.

Списочное включение ты уже знаешь:

    [x * x for x in range(5)]     -> [0, 1, 4, 9, 16]   список, всё в памяти

Замени квадратные скобки на круглые - и получится генераторное выражение:

    (x * x for x in range(5))     -> генератор, значений пока нет вообще

Синтаксис почти тот же, а поведение разное: список считает всё сразу,
генератор - по одному значению, когда его попросят.
"""

import sys


def demo3():
    print("== 03. Генераторные выражения ==\n")

    print("-- квадратные скобки против круглых --")
    as_list = [x * x for x in range(5)]
    as_gen = (x * x for x in range(5))
    print("  список   :", as_list)
    print("  генератор:", as_gen, "-> list():", list(as_gen))

    print("\n-- разница видна на объёме (1 млн значений) --")
    print("  [x*x for x in range(1_000_000)] :",
          sys.getsizeof([x * x for x in range(1_000_000)]), "байт")
    print("  (x*x for x in range(1_000_000)) :",
          sys.getsizeof(x * x for x in range(1_000_000)), "байт")

    print("\n-- с функциями-потребителями скобки не дублируем --")
    # sum, max, min, any, all, sorted, ' '.join - принимают любой итератор.
    # Ни одного промежуточного списка здесь не создаётся.
    print("  sum(x * x for x in range(1_000_000)) =",
          sum(x * x for x in range(1_000_000)))
    print("  max(len(w) for w in ['да', 'привет', 'ок']) =",
          max(len(w) for w in ["да", "привет", "ок"]))

    print("\n-- any / all: выходят на первом же ответе --")
    words = ["ошибка сети", "всё хорошо", "ok"]
    # any останавливается, как только нашёл первое True: остальные строки
    # даже не проверяются. На больших данных это экономит уйму работы.
    print("  есть строка со словом 'ошибка'?", any("ошибка" in w for w in words))
    print("  все строки короче 20 символов?", all(len(w) < 20 for w in words))

    print("\n-- фильтр внутри выражения (if справа) --")
    numbers = range(1, 11)
    evens = (n for n in numbers if n % 2 == 0)
    print("  чётные:", list(evens))

    print("\n-- то же и для словарей/множеств (но там скобки = уже готовый объект) --")
    prices = {"чай": 120, "кофе": 250, "какао": 180}
    cheap = {name: price for name, price in prices.items() if price < 200}
    print("  словарное включение:", cheap)
    print("  сумма всех цен:", sum(prices.values()))

    print("\nИтог: круглые скобки - ленивый генератор, квадратные - готовый список.")
    print("Нужен результат целиком, по индексу или несколько раз - список.")
    print("Надо просто просуммировать/проверить/пройти один раз - генератор.")


if __name__ == "__main__":
    demo3()
