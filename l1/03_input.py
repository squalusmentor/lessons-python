# Урок 3 — Ввод от пользователя (input)

# input() останавливает программу и ждёт, пока пользователь что-то напишет
# Всегда возвращает СТРОКУ (str) — это важно!

imya = input("Как тебя зовут? ")
print(f"Привет, {imya}!")

# --- Числа через input ---
# Чтобы работать с числом, нужно преобразовать строку → int или float
age_str = input("Сколько тебе лет? ")
age = int(age_str)  # str → int

print(f"Тебе {age} лет.")
print(f"Через 5 лет будет {age + 5} лет.")

# Можно сразу в одну строку:
chislo = float(input("Введи любое число: "))
print(f"Твоё число: {chislo}")
print(f"Умноженное на 2: {chislo * 2}")
print(f"Квадрат числа: {chislo ** 2}")

# --- Мини-калькулятор ---
print("\n--- Мини-калькулятор ---")
x = float(input("Первое число: "))
y = float(input("Второе число: "))

print(f"{x} + {y} = {x + y}")
print(f"{x} - {y} = {x - y}")
print(f"{x} * {y} = {x * y}")

if y != 0:
    print(f"{x} / {y} = {round(x / y, 4)}")
else:
    print("На ноль делить нельзя!")
