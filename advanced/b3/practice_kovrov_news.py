"""
Урок B3 — ПРАКТИЧЕСКАЯ РАБОТА
Декораторы на реальной задаче: парсим «Последние новости» с сайта Коврова.

Идея проекта: тянем главную страницу https://kovrov-gorod.ru/ (официальный
сайт администрации города), вытаскиваем через bs4 все заголовки блока
«Последние новости» и ссылки на полные тексты. Функции, работающие с сетью и
селекторами, защищаем СВОИМИ декораторами: что бы ни случилось (таймаут,
пропавший селектор), наружу всегда уходит аккуратная JSON-строка со статусом —
ни одного голого исключения.

Тебе ДАНА одна рабочая функция — fetch_html(url) — она скачивает страницу и
возвращает HTML строкой (кодировка уже учтена). Твоя задача — написать
декораторы, функции-добытчики и demo().


====================================================================
ШАГ 0. Разведка
--------------------------------------------------------------------
Запусти файл: python practice_kovrov_news.py — увидишь фрагмент HTML вокруг
блока новостей. Сайт статический: контент лежит прямо в HTML, JS для парсинга
не нужен (можешь убедиться сам: curl -s https://kovrov-gorod.ru/).

Обрати внимание в коде fetch_html на строку с response.encoding: сайт живёт в
windows-1251, а сервер кодировку в заголовках не сообщает. Закомментируй её и
посмотри, во что превращается русский текст.

Найди в выведенном фрагменте структуру блока (или посмотри в DevTools):

  <div id="newsbox">           — контейнер блока «Последние новости»
    <div class="newsitem">     — одна новость
      <h3>...</h3>             — заголовок
      <div class="pub-date">   — дата публикации
      <div class="nextnews">
        <a href="/press/news/NNNNN.html">  — ссылка «подробнее»

Из этой структуры собери CSS-селекторы для заголовков и ссылок.


====================================================================
ШАГ 1. Декоратор catch_network(errormessage)
--------------------------------------------------------------------
Декоратор С ПАРАМЕТРОМ (три уровня вложенности, как file_decorator из B3.3)
для функций, которые ходят в сеть. Поведение:

  - функция отработала -> вернуть её результат КАК ЕСТЬ;
  - requests.exceptions.Timeout     -> вернуть JSON-строку вида
        {"status": "error", "error": "timeout", "message": errormessage}
  - requests.exceptions.ConnectionError -> такой же JSON, но "error": "connection".

JSON собирай через json.dumps(..., ensure_ascii=False) — иначе русский текст
превратится в \\uXXXX. Не забудь @functools.wraps на обёртке.


====================================================================
ШАГ 2. Декоратор guard_selector(errormessage)
--------------------------------------------------------------------
Декоратор для функций, которые вынимают данные по CSS-селектору. Эти функции
возвращают список найденного. Поведение обёртки:

  - список НЕ пустой -> вернуть JSON-строку
        {"status": "ok", "count": <сколько>, "data": [...]}
  - список пустой или None -> вернуть JSON-строку
        {"status": "error", "error": "элемент не найден", "message": errormessage}

Подумай: где здесь пригодится захват errormessage замыканием через два уровня?
И снова — functools.wraps.


====================================================================
ШАГ 3. Функции-добытчики
--------------------------------------------------------------------
  fetch_html(url)            — ДАНА (ниже). Навесь на неё @catch_network,
                               просто добавив строку над def.

  get_news_titles(html)      — @guard_selector("заголовки не найдены").
                               Принимает HTML строкой, возвращает СПИСОК СТРОК —
                               заголовки всех новостей блока (select + get_text).

  get_news_links(html)       — @guard_selector("ссылки не найдены").
                               Возвращает список ПОЛНЫХ url на тексты новостей:
                               достань атрибут href у ссылок «подробнее» и
                               преобразуй через urljoin(BASE_URL, href).

Чтобы декоратор guard_selector было удобно проверять на «плохом» селекторе,
сделай селектор НЕобязательным параметром функции, например:
  def get_news_titles(html, selector="#newsbox .newsitem h3")


====================================================================
ШАГ 4. demo()
--------------------------------------------------------------------
Напиши функцию demo(), которая:

  1. Качает страницу: fetch_html(BASE_URL). Результат — либо HTML, либо
     JSON-строка об ошибке: отличи их и обработай (подсказка: json.loads +
     проверка "status"; или просто проверь, что строка начинается с "{").
  2. Печатает нумерованный список заголовков из get_news_titles
     (json.loads -> проверка status -> data).
  3. Печатает ссылки из get_news_links.
  4. Показывает, что декораторы работают:
     - вызови get_news_titles с заведомо несуществующим селектором
       (например, "#newsbox .no-such-class h3") и напечатай ответ —
       должен прийти JSON «элемент не найден»;
     - вызови fetch_html с timeout=0.001 и напечатай ответ — должен прийти
       JSON про таймаут (для этого пробрось timeout параметром в fetch_html).

Сайт при отладке не дёргай в цикле: скачай HTML один раз в переменную и гоняй
добытчики по ней.
"""

import functools
import json
from urllib.parse import urljoin

import requests
from bs4 import BeautifulSoup


BASE_URL = "https://kovrov-gorod.ru/"


def fetch_html(url: str, timeout: float = 10) -> str:
    """Скачивает страницу и возвращает HTML строкой.

    Сервер не сообщает кодировку в заголовках, поэтому requests по умолчанию
    решит, что это latin-1, и русский текст сломается. Выставляем руками:
    сайт отдаёт windows-1251 (видно в <meta charset> страницы).
    Таймаут и ошибки сети не глушит — их должен ловить твой декоратор.
    """
    response = requests.get(url, timeout=timeout)
    response.raise_for_status()
    response.encoding = "windows-1251"
    return response.text


if __name__ == "__main__":
    html = fetch_html(BASE_URL)
    marker = "Последние новости"
    position = html.find(marker)
    print(html[position:position + 1500])
