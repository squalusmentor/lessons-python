"""
Урок B2 — ПРАКТИЧЕСКАЯ РАБОТА, ЧАСТЬ 2
ООП на реальных данных: георазведка публичных IP-адресов.

Идея проекта: берём публичные IP, тянем по ним геоданные с бесплатного API
ip-api.com (JSON, без ключа и регистрации), превращаем сырые словари в ОБЪЕКТЫ,
раскладываем их по классам (категоризация), а потом считаем статистику и ищем
через методы. Это применение всего занятия 2 на живых данных.

Тебе ДАНА одна рабочая функция — fetch_ip_info(ip) — она возвращает сырой JSON
как dict. Твоя задача — превратить эти сырые данные в объекты и написать demo().


====================================================================
ШАГ 0. Разберись с данными
--------------------------------------------------------------------
Запусти файл: python practice_ip_geo_part2.py — увидишь сырой JSON для 8.8.8.8.

Обрати внимание на три флага: hosting / mobile / proxy (true/false). По ним
будем раскладывать IP-адреса по типам. Не все поля всегда заполнены (например,
"org" иногда пустая строка).


====================================================================
ШАГ 1. Иерархия классов
--------------------------------------------------------------------
Имена классов — ровно такие:

  Host             — базовый класс. Хранит данные одного IP: адрес, страну,
                     город, координаты (lat/lon), провайдера, ASN, континент.
  DataCenterHost   — хост из дата-центра / облака         (hosting == True)
  MobileHost       — адрес мобильного оператора            (mobile == True)
  ProxyHost        — прокси, VPN или анонимайзер            (proxy == True)
  ResidentialHost  — обычный домашний адрес     (все три флага == False)

У каждого подкласса Host должен быть свой метод category(), возвращающий
название типа строкой. Базовый Host.category() тоже должен что-то возвращать
на случай, если ни один флаг не совпал.


====================================================================
ШАГ 2. Фабрика
--------------------------------------------------------------------
В классе Host сделай classmethod from_raw(raw: dict), который смотрит на флаги
в сыром словаре и создаёт объект нужного подкласса. Фабрика нужна, чтобы в
demo() не писать if/elif по каждому IP — просто передаёшь словарь и получаешь
готовый объект.

Порядок проверки флагов реши сам — что будет приоритетнее, если вдруг несколько
флагов True одновременно.


====================================================================
ШАГ 3. HostCatalog
--------------------------------------------------------------------
Сценарий: ты получил список IP из логов и хочешь понять, кто к тебе ходил —
боты из датацентров, живые пользователи или анонимайзеры. HostCatalog — это
анализатор такого списка.

Напиши класс HostCatalog, который СОДЕРЖИТ хосты внутри и реализует:

  add(host)            — добавить хост; если IP уже есть, не дублировать
  by_country(name)     — вернуть список хостов из указанной страны
  stats()              — вернуть словарь {категория: количество}, где категория —
                         это то, что возвращает host.category()

  и dunder-методы, чтобы работали: len(catalog), for host in catalog,
  "1.1.1.1" in catalog.


====================================================================
ШАГ 4. demo()
--------------------------------------------------------------------
Напиши функцию demo(), которая:

  1. Запрашивает все SAMPLE_IPS через fetch_ip_info и фабрикой превращает
     в объекты (Host.from_raw).
  2. Добавляет их в HostCatalog.
  3. Печатает для каждого хоста: IP, страну, провайдера и category().
  4. Печатает stats() — сводку по типам.
  5. Берёт страну первого хоста и печатает все хосты из той же страны
     через by_country().
"""

import json
import ipaddress
from urllib.parse import urlencode
from urllib.request import urlopen


_API_URL = "http://ip-api.com/json"
_FIELDS = ("status,message,continent,country,countryCode,regionName,city,"
           "lat,lon,timezone,isp,org,as,mobile,proxy,hosting,query")

# Публичные адреса для экспериментов (DNS-провайдеры и пара известных сервисов).
SAMPLE_IPS = [
    "8.8.8.8",          # Google DNS        (дата-центр)
    "1.1.1.1",          # Cloudflare DNS    (дата-центр)
    "208.67.222.222",   # OpenDNS           (дата-центр)
    "9.9.9.9",          # Quad9 DNS         (дата-центр)
    "77.88.55.88",      # обычный
    "45.84.59.251",     # мой сервер
]


def fetch_ip_info(ip: str) -> dict:
    """Запрашивает геоданные о ПУБЛИЧНОМ IP с ip-api.com и возвращает сырой JSON (dict).

    Берёт только публичные адреса: приватные и зарезервированные (127.0.0.1,
    192.168.x.x, 10.x.x.x и т.п.) отклоняются с ValueError.
    Требует доступ в интернет. Ошибки сети/API не глушит — пусть всплывают.
    """
    address = ipaddress.ip_address(ip)        # ValueError, если строка — не IP
    if not address.is_global:
        raise ValueError(f"{ip}: нужен публичный IP (приватные/служебные не берём)")

    url = f"{_API_URL}/{ip}?{urlencode({'fields': _FIELDS})}"
    with urlopen(url, timeout=10) as response:
        raw = json.load(response)

    if raw.get("status") != "success":
        raise RuntimeError(f"ip-api вернул ошибку для {ip}: {raw.get('message', 'unknown')}")
    return raw


if __name__ == "__main__":
    info = fetch_ip_info(SAMPLE_IPS[0])
    print(json.dumps(info, indent=2))
